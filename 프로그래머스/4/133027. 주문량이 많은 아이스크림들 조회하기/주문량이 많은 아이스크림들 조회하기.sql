SELECT A.FLAVOR
FROM (SELECT FLAVOR, TOTAL_ORDER
FROM FIRST_HALF

UNION ALL

SELECT FLAVOR, TOTAL_ORDER
FROM JULY) AS A
GROUP BY A.FLAVOR
ORDER BY SUM(A.TOTAL_ORDER) DESC
LIMIT 3














